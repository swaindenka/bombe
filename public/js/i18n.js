function detectLang() {
  try {
    const saved = localStorage.getItem('bombe.lang');
    if (saved === 'tr' || saved === 'en') return saved;
  } catch {}
  return (navigator.language || 'tr').toLowerCase().startsWith('tr') ? 'tr' : 'en';
}

let current = detectLang();

export const getLang = () => current;

export function setLang(lang) {
  current = lang === 'en' ? 'en' : 'tr';
  document.documentElement.lang = current;
  try {
    localStorage.setItem('bombe.lang', current);
  } catch {}
}

export function t(key, params) {
  let s = (STR[current] && STR[current][key]) ?? STR.tr[key] ?? key;
  if (params) for (const [k, v] of Object.entries(params)) s = s.replaceAll(`{${k}}`, v);
  return s;
}

export const bombText = (lang, key) => (BOMB_STR[lang] || BOMB_STR.tr)[key];
export const moduleName = (type, lang = current) => (MODULE_NAMES[lang] || MODULE_NAMES.tr)[type] || type;

document.documentElement.lang = current;
